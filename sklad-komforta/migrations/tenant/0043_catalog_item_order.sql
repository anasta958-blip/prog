ALTER TABLE catalog_items ADD COLUMN sort_order bigint GENERATED BY DEFAULT AS IDENTITY;

-- Preserve the previous visible order for existing data.
WITH ordered AS (
    SELECT id, row_number() OVER (ORDER BY updated_at DESC, id) AS position
    FROM catalog_items
)
UPDATE catalog_items AS item SET sort_order = ordered.position
FROM ordered WHERE ordered.id = item.id;

SELECT setval(pg_get_serial_sequence('catalog_items', 'sort_order'),
    COALESCE((SELECT max(sort_order) FROM catalog_items), 1),
    EXISTS (SELECT 1 FROM catalog_items));

CREATE INDEX ix_catalog_items_sort_order ON catalog_items (sort_order, id)
    WHERE deleted_at IS NULL;
